const assert = require('assert');
const P = require('../parser.js');
assert.strictEqual(P.categorize('', 'ร้าน อเมซอน สาขาสยาม'), 'food');
assert.strictEqual(P.categorize('', 'การไฟฟ้านครหลวง MEA'), 'bills');
assert.strictEqual(P.categorize('', 'บัตรกรุงไทย KTC'), 'cc');
assert.strictEqual(P.categorize('', 'PTT Station'), 'travel');
assert.strictEqual(P.categorize('', 'นางสาว สมหญิง รักดี'), 'transfer');
assert.strictEqual(P.categorize('', 'hairsalon'), 'health', 'ais ต้องไม่ไปจับใน hairsalon');
assert.strictEqual(P.categorize('', 'xyz'), 'other');
const n = P.normalizeAI({ is_slip: true, amount: '1,250.505', date: '2026-10-31', time: '9:5', merchant: ' 7-Eleven ', category: 'bogus' });
assert.deepStrictEqual(n, { isSlip: true, amount: 1250.51, date: '2026-10-31', time: null, merchant: '7-Eleven', category: 'grocery' });
assert.strictEqual(P.normalizeAI({ amount: -5, date: '31/10/2026' }).amount, null);
assert.strictEqual(P.normalizeAI({ amount: -5, date: '31/10/2026' }).date, null);
assert.strictEqual(P.normalizeAI({ is_slip: false }).isSlip, false);
assert.ok(P.AI_PROMPT.includes('cc=ชำระบัตรเครดิต'));
console.log('parser ok');
